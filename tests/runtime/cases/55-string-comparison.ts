// 第 177 轮：**字符串比较**（`"a" < "b"`）。
//
// 四条关系（`<` `<=` `>` `>=`）原来一律走 `NumericOf` ✗——只认数字 ✓，
// 于是 `"a" < "b"` 报 `unimplemented: arithmetic on a non-numeric operand` ✗，
// **整份文件进不来** ✓。而比较字符串在普通 `.ts` 里遍地都是 ✓：
// 排序、版本号、`if (a < b)`、`"10" < "9"` 这类文本序的判断 ✓。
// 这是第 176 轮那份 69 条普查抓出来的**第一条** ✓。
//
// JS 的口径（`Abstract Relational Comparison`）只有三层，而且**四条关系不是四个语义** ✓：
// `a > b` 就是 `b < a` ✓、`a <= b` 就是 `!(b < a)` ✓。所以这一轮把它们收成**一处判据**
// （`rt.xl.md` 的 `CompareValues` ✓，返回 `-1 / 0 / 1 / -2`，其中 `-2` 是「有 `NaN` 参与」
// ⇒ 四条关系一律 `false` ✓）：
//
//   1. **两边都是字符串** → 逐**码元**比（UTF-16 码元序，不是码点序）；
//   2. **其余** → 两边各做一次 `ToNumber` 再按数值比；
//   3. `NaN` 参与 → `-2`（四条全是 `false`）。
//
// 第 2 层同时盖住「一边是字符串、一边是数值」：`"10" < 9` 为假而 `"10" < "9"` 为真 ——
// JS 只在**两边都是字符串**时才按文本比。只做一层（都按文本或都按数值）会**错掉一半**。

// ① 字符串按码元序（含「长的那条更大」与大小写：码元里 `Z`(90) < `a`(97)）
console.log("a" < "b", "b" < "a", "a" <= "a", "a" >= "b");
console.log("ab" < "abc", "abc" <= "ab", "Z" < "a", "10" < "9");

// ② 一边字符串一边数值：字符串先 ToNumber
console.log("10" < 9, 1 < "2", 9 >= "10", "2" > 10);

// ③ NaN 参与的六种组合（四条关系一律 false —— 这一族最容易写成「相等」）
console.log(NaN < 1, NaN > 1, NaN <= 1, NaN >= 1, 1 < NaN, 1 >= NaN);

// ④ undefined 给 NaN、null 给 0、布尔给 1/0（JS 的 ToNumber）
console.log(undefined < 1, undefined >= 1, null < 1, null > -1, true < 2, false <= 0);

// ⑤ 负零：`-0 < 0` 为假、`-0 >= 0` 为真
console.log(-0 < 0, -0 >= 0);

// ⑥ 代理对：UTF-16 码元序下 `😀`（0xD83D 打头）排在 `\uFFFF` **前面**
console.log("😀" > "\uFFFF", "\uD83D" < "\uFFFF");

// ⑦ 真实用法：默认排序就是按码元比
//
// **自定义比较器那一版不在这份语料里** ✗：`(x, y) => (x < y ? -1 : x > y ? 1 : 0)`
// 这样的形状**本仓解析就错了** ✗（`<` 被判成泛型实参、`y ? -1 : x` 成了类型实参 ✓），
// 于是它给的是**静默错值** ✗（第 177 轮量到的最小反例 ✓，记在台账里 ✓）。
// 这一条与比较语义无关 ✓——把 `==` 换成 `<` 就复现 ✓，而在**语句层**写同样的嵌套三元是对的 ✓，
// 只有**箭头函数体里**这一处错 ✓。**下一轮修它** ✓（先补语料、再按 TS 的 AST 对拍 ✓）。
const words = ["b", "a", "c", "aa"];
console.log(words.slice().sort().join(","));
