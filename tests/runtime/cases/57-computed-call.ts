// 第 179 轮：**零实参的计算成员调用**（`xs[0]()` —— 从表里取一个再调）。
//
// 第 178 轮修好了「有实参」那一半（`cbs[0](3)` 原来抛 `property keys must be strings or symbols`），
// 但**零实参**那一半还错着，而且是**静默错值**：
//
//   console.log(xs[0]());      // Node 给 1；本仓给的是**函数本身**
//
// 两处根因（都在**投影**这一层，token 树一直是对的）：
//
// ① `Method.PrintAst` 的实参过滤把**所有空括号**都当成「被调用者自己那一对」滤掉了 ✗——
//    而零实参的调用本身**根本不贡献括号**（`f()` 的产物是 `<Method name="f"></Method>` ✓），
//    所以一个空 `(` 出现在 `kids` 里只可能是**实参自己那一段里的调用** ✓。
//    修法：空括号只在「它是第一个子单元」或「被调用者是 `NotNull`」时才滤 ✓。
// ② `xs[0]() + 1` 是**另一种形状**：那一对空括号被卷进了**二元单元的最左边**
//    （`[PropertyAccess(xs, [0]), BinaryOperator(Bracket(空), +, 1)]` ✓），
//    投影的二元那一支于是把它当成左操作数（空的 `ParenthesizedExpression`）✗。
//    修法：`print-ast-common.xl.md` 的 0e 支——沿左脊柱找到那个空括号 ✓，
//    把前一个兄弟投出来、套一层零实参的 `CallExpression`，再照常折运算符 ✓。
//
// 这一份语料把**四个位置**都钉住：实参表里 ✓、二元左操作数里 ✓、
// 比较 / 逻辑 / 空值合并里 ✓、以及**回归**那两条（`b!()` / `b?.()` 的空括号是**调用自己的** ✓）。

const xs = [() => 1, () => 2];
const obj: any = { m: () => 7 };

// ① 实参表里（原来给的是函数本身）
console.log(xs[0]());

// ② 多个实参、多个调用
console.log(xs[0](), xs[1]());

// ③ 二元 / 比较 / 逻辑 / 空值合并的左操作数（原来给的是函数本身）
console.log(xs[0]() + 1, xs[0]() + 1 + 2, xs[0]() * 3);
console.log(xs[0]() > 0, xs[0]() && "y", xs[0]() ?? 9);

// ④ 字符串键那一路（回归：它一直是对的）
console.log(obj["m"]() + 1);

// ⑤ 回归：`!` 与 `?.` 后面那对空括号是**调用自己的**实参表，不该变成实参
const n: any = () => 3;
console.log(n!(), obj.m?.(), obj.n?.());
