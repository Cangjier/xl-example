// 第 180 轮：**逗号运算符**（`(1, 2)` · `for` 的递增段 · 一串赋值）。
//
// 它是**糖**：左边只求值（副作用留着），值就是右边 ✓；**顺序是语义**（先左后右）。
// 这一轮之前它整族报 `unimplemented: binary operator ,`（**整份文件进不来**），
// 而 `for (let i = 0, j = 3; i < j; i++, j--)` 这种写法在日常代码里到处都是。
//
// 关掉它要动**两处**（都在执行侧，投影那一侧本来就与 TS 一致）：
//
//  ① 降级：逗号落成控制流（先算左边、再算右边、结果取右边那一格），不进 id 表；
//  ② **投影的优先级**：`a = 1, b = 2` 里赋值号的右操作数**只到下一个顶层逗号为止**——
//     原来 `=` 那一支会把后面整串都当成右操作数（`a = (1, b) = 2`），
//     形状这一层就错了（`cases:tsast` 一量就红）。
//
// 顺带修掉一处**潜伏的水位 bug**（`LowerInto` 无条件 `Release(value)`）：
// 赋值表达式的「值」是**左值自己那一格**，退到它那里会把框架里所有活着的槽一起退掉，
// 于是 `a = 1, b = 2, c = 3` 里内层逗号拿到 `a` 的槽、把 `a` 写成 3（Node 给 1）——
// 而**两段**的 `a = 1, b = 2` 看不出问题（内层结果正好又被外层覆盖），是最难查的一种。

// ① 括号里的逗号表达式（值是最右边那个）
const a = (1, 2);
console.log(a);

// ② for 的递增段（TS 那边那个 incrementor 就是一个逗号表达式）
let s = 0;
for (let i = 0, j = 3; i < j; i++, j--) s++;
console.log(s);

// ③ 一串赋值（逗号比赋值松：每个 `=` 各绑自己那一段）
let x = 0;
let y = 0;
let z = 0;
x = 1, y = 2, z = 3;
console.log(x, y, z);

// ④ 赋值与逗号混着写（水位那一处就出在这形状上）
let m = 0;
let n2 = 0;
m = 1, n2 = 2, m = m + n2;
console.log(m, n2);

// ⑤ 箭头体、表达式位、以及「左边真的有副作用」
const f = () => (1, 2);
console.log(f(), (9, 8), (true, "v"));
let calls = 0;
function tick(v: number) { calls += v; return v; }
const r = (tick(1), tick(2));
console.log(r, calls);

// ⑥ 嵌套与三元一起（顺序仍然是先左后右）
let t = 0;
const q = (t = 1, t > 0 ? "pos" : "neg");
console.log(q, t);
