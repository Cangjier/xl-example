// 第 156 轮：`?.` 链在 token 层是**几格**，`??` 不能只跟尾巴结合。
//
// **症状**：`o?.b?.c ?? 0` **静默**给 `{ c: 2 }`（JS 给 `2`）——
// 投影投出来只剩前半截（`o?.b`）。
//
// **根因**：二元运算符重组只看「紧挨着的那一格」，而这一格是**链的尾巴** `NCO(c)`，
// 于是 `??` 与尾巴结合、`o` 与 `NCO(b)` 留在外面。
//
// **修法**：当 NCO 前面**还是** NCO 时，往前把整条链收进来（起点是基名）。
// 判据刻意收紧到这一种：第一版对所有 NCO 都收，`cases:tsast` 当场从 1430 掉到 1428。
//
// 顺带量到：单条 `?.` 与 `??` 的组合（`o?.k ?? 9`）**一直都是对的**，
// 所以这一轮一个字节都没动它——回归那一格留在判据里。

const box: any = { b: { c: 2 }, k: 1, deep: { nested: { v: 5 } } };

// ① 两条 `?.` 之后跟 `??`（这一轮修好的形状）
console.log(box?.b?.c ?? 0, box?.x?.y ?? "fallback", box?.deep?.nested?.v ?? -1);

// ② 单条 `?.` + `??`（本来就是对的，当回归）
console.log(box?.k ?? 9, box?.missing ?? "none", box?.b.c ?? 0);

// ③ 链后面跟别的东西，一起确认没被切坏
console.log(box?.b?.c + 1, box?.b?.c === 2, (box?.b?.c ?? 0) * 10);

// ④ 短路那一半：前面断了，整条链给 undefined，再由 `??` 兜住
const gone: any = null;
console.log(gone?.b?.c ?? "null-chain", gone?.b?.c ?? 0);
