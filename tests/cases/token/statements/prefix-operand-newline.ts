// xl:note 前缀一号运算符的**操作数写在下一行**（第 934 轮第五批普查量出的 `incdec-n5` 一族）：
// `a++; --` 换行 `a;` 在 TS 那边是一条 `PrefixUnaryExpression`（`--` 要操作数，ASI 不在它
// 前面断句），而判据 `Statement.EndsOperand` 原来只问「是不是运算符」——解析期 `;` 收壳之后
// 它左边那一格已经是**一条成形的 `Statement`**，而整条语句**不是**操作数。
// 守卫八格：三种前缀（`--` / `++` / `!`）、跨行注释那一版、块语句之后、以及**反方向**
// （后缀 `++` 换行之后另起一条前缀，那两档本来就该是两条语句）。
// xl:round 934
// xl:end
let a = 1; a++; --
a;
let b = 1; b++; --//c
b;
let c = 1; c++; ++
c;
let d = 1; d++; !
d;
if (a) { a++; } --
a;
let e = 1; e++
++e;
let f = 1; f++
--f;
let g = 1; g++;
--g;
